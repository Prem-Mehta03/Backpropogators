"""Role 3 interface. Reading IDs double as run-local evidence IDs."""

from typing import Protocol, runtime_checkable
from evaluation.role4.contracts.events import SensorObservation


@runtime_checkable
class SensorimotorPort(Protocol):
    def reset(self, scenario_id: str) -> None: ...
    def read_lidar(self) -> SensorObservation: ...
    def read_camera(self) -> SensorObservation: ...
    def get_environment_state(self) -> dict: ...
    def get_environment_revision(self) -> int: ...
